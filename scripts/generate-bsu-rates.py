"""Build the display data from the reviewed annual CSV; verify against monthly data."""
import csv
import json
import sys
from collections import defaultdict
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path

root = Path(__file__).resolve().parent.parent
monthly = defaultdict(list)
with (root / 'research/bsu-rentehistorikk.csv').open() as stream:
    for row in csv.DictReader(stream):
        monthly[row['måned'][:4]].append(row)
with (root / 'research/bsu-rente-arssnitt-2018-2026.csv').open() as stream:
    annual = list(csv.DictReader(stream))
assert [row['år'] for row in annual] == list(monthly)
SHORT = ['jan.', 'feb.', 'mars', 'apr.', 'mai', 'juni', 'juli', 'aug.', 'sep.', 'okt.', 'nov.', 'des.']
rows = []
for row in annual:
    months = monthly[row['år']]
    assert len(months) == int(row['antall måneder'])
    last = row['år'] == annual[-1]['år']
    # Bare siste år kan være et delår. Kildevakt legger til nye måneder via PR.
    assert len(months) == 12 or (last and 1 <= len(months) < 12), (row['år'], len(months))
    for key in ['BSU prosent', 'bundne innskudd prosent']:
        mean = (sum(Decimal(m[key]) for m in months) / len(months)).quantize(Decimal('.01'), rounding=ROUND_HALF_UP)
        assert mean == Decimal(row[key]), (row['år'], key, mean, row[key])
    label = row['år']
    if len(months) < 12:
        label += ' (jan.)' if len(months) == 1 else f" (jan. til {SHORT[len(months) - 1]})"
    rows.append([label, float(row['BSU prosent']), float(row['bundne innskudd prosent'])])
data = {'caption': 'Gjennomsnittlig innskuddsrente for husholdninger, prosent', 'columns': ['År', 'BSU', 'Bundne innskudd'], 'rows': rows, 'note': 'Snitt per år, regnet fra SSBs månedstall. Renten varierer med rentenivået i samfunnet. Tidligere renter sier ikke hva renten blir framover.'}
text = '// Generated by scripts/generate-bsu-rates.py. Edit the CSV, not this file.\n(function(root){\nconst data=' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\nif(typeof module!=="undefined"&&module.exports)module.exports=data;else root.SpareBsuRates=data;\n})(typeof window!=="undefined"?window:globalThis);\n'
target = root / 'dist/bsu-rates.js'
if '--check' in sys.argv:
    assert target.read_text() == text, 'Regenerate dist/bsu-rates.js'
else:
    target.write_text(text)
print(f'BSU: {2 * len(annual)} årssnitt kontrollert mot {sum(len(m) for m in monthly.values())} månedstall; visningsdata samsvarer.')
